#!/usr/bin/env python3
"""Generate docs/CONTROLS.md from catalog/controls.tsv and tools/deviations.tsv.

usage: python3 tools/gen_controls_md.py > docs/CONTROLS.md
"""
import csv
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

cat = list(csv.DictReader(open(os.path.join(ROOT, "catalog", "controls.tsv"), encoding="utf8"), delimiter="\t"))
dev = {}
with open(os.path.join(HERE, "deviations.tsv"), encoding="utf8") as f:
    for row in csv.DictReader(f, delimiter="\t"):
        dev[row["id"]] = row["note"]

l1 = [r for r in cat if r["srv_level"] == "1"]
unknown = set(dev) - {r["id"] for r in l1}
if unknown:
    sys.exit("deviations for unknown Level 1 controls: %s" % sorted(unknown))


def esc(s):
    return s.replace("|", "\\|")


def how(r):
    t = r["check_type"]
    p = r["params"]
    if t == "custom":
        return "custom (`cus_%s`)" % r["id"].replace(".", "_")
    if p != "-" and t in ("sysctl", "kmod_unavailable", "mount_opt"):
        return "%s (%s)" % (t, p.replace(";", ", "))
    return t


out = []
out.append("# Controls covered by cis-audit 1.0.0\n")
out.append("Generated by `tools/gen_controls_md.py` from `catalog/controls.tsv` and `tools/deviations.tsv`; do not edit by hand.\n")
out.append("CIS Ubuntu Linux 26.04 LTS Benchmark v1.0.0, profile Level 1 - Server: %d recommendations. "
           "The catalog holds all %d recommendations; the %d Level 2 - Server rows are reported as SKIPPED / NOT IMPLEMENTED.\n"
           % (len(l1), len(cat), len(cat) - len(l1)))
out.append("## Check types\n")
c = Counter(r["check_type"] for r in l1)
out.append("| Check type | Level 1 - Server rows |\n| --- | ---: |")
for k, v in sorted(c.items(), key=lambda kv: -kv[1]):
    out.append("| %s | %d |" % (k, v))
out.append("")
out.append("## Deviations from the PDF and open points\n")
out.append("Where the benchmark text, the plan and the tooling disagree, the PDF decides. The list below is every place where this "
           "script is stricter, looser or different from the PDF's literal audit text, or where the PDF could not be followed "
           "because the audit is read-only.\n")
out.append("| ID | Note |\n| --- | --- |")
for r in l1:
    if r["id"] in dev:
        out.append("| %s | %s |" % (r["id"], esc(dev[r["id"]])))
out.append("")
out.append("## All Level 1 - Server controls\n")
out.append("| ID | Recommendation | Assessment | Check | Applies if | Slow |\n| --- | --- | --- | --- | --- | --- |")
for r in l1:
    out.append("| %s | %s | %s | %s | %s | %s |" % (
        r["id"], esc(r["title"]), r["assessment"], esc(how(r)),
        "" if r["applies_if"] == "-" else "`%s`" % r["applies_if"], "yes" if r["slow"] == "1" else ""))
out.append("")
sys.stdout.reconfigure(newline="\n")
sys.stdout.write("\n".join(out))
