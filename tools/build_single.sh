#!/usr/bin/env bash
# tools/build_single.sh - bundle everything into dist/cis-audit.sh.
#
# Inlines lib/*.sh and lib/checks_custom/*.sh in the order cis-audit.sh sources them
# and embeds catalog/controls.tsv as a heredoc, so dist/cis-audit.sh runs on its own.
# site.conf and exceptions.conf stay external and optional.
set -eu
HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT=$HERE/..
OUT=${1:-$ROOT/dist/cis-audit.sh}
LIBS=(core facts applicability checks_generic
    checks_custom/s1_initial_setup checks_custom/s2_services checks_custom/s3_network
    checks_custom/s4_firewall checks_custom/s5_access checks_custom/s6_logging
    checks_custom/s7_maintenance exceptions report_text report_html)

# every library must be sourced by cis-audit.sh (keeps the two lists in step)
block=$(sed -n '/@@LIBS_BEGIN/,/@@LIBS_END/p' "$ROOT/cis-audit.sh")
for l in "${LIBS[@]}"; do
    grep -qF "$l" <<<"$block" || { echo "library $l is missing from the list in cis-audit.sh" >&2; exit 1; }
done

mkdir -p "$(dirname -- "$OUT")"
state=0
{
    while IFS= read -r line || [[ -n $line ]]; do
        case $state in
            0)
                if [[ $line == *"@@LIBS_BEGIN"* ]]; then
                    state=1
                    printf '# ---- bundled libraries (generated by tools/build_single.sh) ----\n'
                    for l in "${LIBS[@]}"; do
                        printf '\n# ==== lib/%s.sh ====\n' "$l"
                        tail -n +2 "$ROOT/lib/$l.sh"
                    done
                    printf '# ---- end of bundled libraries ----\n'
                elif [[ $line == *"@@CATALOG_BEGIN"* ]]; then
                    state=2
                    printf '# ---- embedded catalog (generated by tools/build_single.sh) ----\n'
                    printf 'catalog_embedded() {\n    cat <<'"'"'CIS_AUDIT_CATALOG_EOF'"'"'\n'
                    cat "$ROOT/catalog/controls.tsv"
                    printf 'CIS_AUDIT_CATALOG_EOF\n}\n'
                else
                    printf '%s\n' "$line"
                fi ;;
            1) [[ $line == *"@@LIBS_END"* ]] && state=0 ;;
            2) [[ $line == *"@@CATALOG_END"* ]] && state=0 ;;
        esac
    done <"$ROOT/cis-audit.sh"
} >"$OUT"
chmod 0755 "$OUT"
bash -n "$OUT"
if command -v sha256sum >/dev/null 2>&1; then
    (cd -- "$(dirname -- "$OUT")" && sha256sum "$(basename -- "$OUT")" >"$(basename -- "$OUT").sha256")
fi
printf 'wrote %s (%s lines)\n' "$OUT" "$(wc -l <"$OUT" | tr -d ' ')"
